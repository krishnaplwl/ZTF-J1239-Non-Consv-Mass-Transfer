#!/usr/bin/env python3
"""
make_tables.py -- regenerate EVERY numerical table of the paper from the raw MESA runs.

    python3 make_tables.py                 # writes paper/tables_generated.tex and results/tables.json
    python3 make_tables.py --skip-qmax     # skip the slow q_max scan (Appendix Table A2)

All numbers come from ztf_j1239_simulations.py (strict mode: raw MESA histories required).
The paper \\input{}s paper/tables_generated.tex, so no table value is typed by hand.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np
from scipy.optimize import brentq

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import ztf_j1239_simulations as sim  # noqa: E402


# ---------------------------------------------------------------- formatting helpers
def n(x, nd=3):
    if x is None or not np.isfinite(x):
        return "--"
    s = f"{x:.{nd}f}"
    if s.startswith("-") and float(s) != 0.0:
        return "$-$" + s[1:]
    return s.lstrip("-") if float(s) == 0.0 else s


def sci(x, nd=2):
    if x is None or not np.isfinite(x):
        return "--"
    m, e = f"{abs(x):.{nd}e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


def table(caption, label, colspec, header, rows, midrules=()):
    out = ["\\begin{table}[!htbp]", "\\centering", f"\\caption{{{caption}}}", f"\\label{{{label}}}",
           "\\maxwidthbox{%", f"\\begin{{tabular}}{{{colspec}}}\\toprule", header + "\\\\\\midrule"]
    for i, r in enumerate(rows):
        if i in midrules:
            out.append("\\midrule")
        out.append(" & ".join(r) + " \\\\")
    out += ["\\bottomrule\\end{tabular}}", "\\end{table}", ""]
    return "\n".join(out)


def split_tables(text: str) -> None:
    """Write each table to paper/tables/<label>.tex so the paper can \\input them where they belong."""
    import re
    tdir = ROOT / "paper" / "tables"
    tdir.mkdir(parents=True, exist_ok=True)
    for blk in re.findall(r"\\begin\{table\}.*?\\end\{table\}", text, flags=re.S):
        lab = re.search(r"\\label\{tab:([^}]*)\}", blk).group(1)
        (tdir / f"{lab}.tex").write_text("% AUTO-GENERATED by make_tables.py\n" + blk + "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-qmax", action="store_true")
    args = ap.parse_args()

    ds = sim.load_or_build_age_grid_dataset(strict=True)
    zeta_fn, rad_fn, _ = sim.make_age_interpolators(ds)
    snap = ds["snap_table"]
    res = json.load(open(ROOT / "results" / "ztf_j1239_simulation_results.json"))
    AG, TG = sim.AGES_GYR, sim.AGE_TAGS
    tex, data = [], {}

    # ------------------------------------------------------------ Table 1: unstripped radii, rho, L_H/L
    rows = []
    for a, t in zip(AG, TG):
        s = snap[t]
        rows.append([f"{a:g}"] + [n(s[m]["R"], 3) for m in sim.MASSES_MJUP] + [n(s[m]["rho"], 3) for m in sim.MASSES_MJUP]
                    + [f"{100 * s[60]['LH_L']:.1f}\\%", f"{100 * s[80]['LH_L']:.1f}\\%"])
    tex.append(table(
        "Unstripped \\texttt{MESA} radii $R\\,[\\RJ]$, contraction rates $\\rho=(\\partial\\ln R/\\partial t)_M\\,[{\\rm Gyr^{-1}}]$ "
        "evaluated \\emph{at} $t_0$ (local quadratic fit of $\\ln R$ vs.\\ $\\ln t$ on $[t_0/1.5,1.5t_0]$) and hydrogen-burning luminosity fractions.",
        "tab:age_snap", "rrrrrrrrrrr",
        "$t_0$ [Gyr] & $R_{20}$ & $R_{40}$ & $R_{60}$ & $R_{80}$ & $\\rho_{20}$ & $\\rho_{40}$ & $\\rho_{60}$ & $\\rho_{80}$ & $(L_{\\rm H}/L)_{60}$ & $(L_{\\rm H}/L)_{80}$",
        rows))

    # ------------------------------------------------------------ Table 2: zeta_ad at node masses
    nodes = [15, 20, 30, 40, 50, 60, 70, 80]
    def zrow(a):
        cen, med = ds["age_zeta_ad"][a][0], ds["age_zeta_ad"][a][1]
        ok = np.isfinite(med)
        return np.interp(nodes, cen[ok], med[ok])
    Z = np.array([zrow(a) for a in AG])
    rows = [[f"{a:g}"] + [n(v, 3) for v in Z[i]] for i, a in enumerate(AG)]
    rows.append(["$1$--$10$ median"] + [n(v, 3) for v in np.median(Z[3:], axis=0)])
    rows.append(["$0.1$--$10$ median"] + [n(v, 3) for v in np.median(Z, axis=0)])
    tex.append(table(
        "Pooled adiabatic donor exponent $\\zeta_{\\rm ad}(\\Md;t_0)$ from the $|\\Mdot|=10^{-6}\\,\\MJ\\,{\\rm yr^{-1}}$ control-subtracted stripping runs "
        "(median over the available runs in $2.5\\,\\MJ$ bins, linearly interpolated to the quoted masses), and medians over the $1$--$10$\\,Gyr and $0.1$--$10$\\,Gyr rows.",
        "tab:age_zeta", "rcccccccc",
        "$t_0$ [Gyr] & $\\Md{=}15$ & $20$ & $30$ & $40$ & $50$ & $60$ & $70$ & $80$", rows, midrules=(9,)))
    data["zeta_nodes"] = {"nodes": nodes, "values": Z.tolist()}

    # ------------------------------------------------------------ Table 3: 60/80 age scaling
    rows = []
    for r in res["age_scaling"]:
        hit = np.isfinite(r["v_imp_60_80_kms"])
        rows.append([f"{r['age_gyr']:g}", n(r["Rd_60_RJ"]), n(r["Ra_80_RJ"]), n(r["zeta_ad_60"]), n(r["q_crit_f0_80"]),
                     n(r["f_crit_pt_60_80"]), n(r["f_crit_fl_60_80"]),
                     n(r["v_imp_60_80_kms"], 1) if hit else "--", n(r["v_esc_80_kms"], 1),
                     n(r["f_max_60_80"]) if hit else "--", n(r["eps_min_fl_60_80"], 2) if hit else "--",
                     n(r["eps_min_fl_dyn_60_80"], 2) if hit else "--", n(r["eps_min_pt_60_80"], 2) if hit else "--",
                     n(r["eps_min_fl_60_80_binary_escape"], 2) if hit else "--",
                     n(r["q_max_fl_80"]) if hit else "--", n(r["q_max_dyn_80"]) if hit else "--"])
    tex.append(table(
        "Stability and stream-energy metrics for $\\Md/\\Ma=60/80\\,\\MJ$ ($q=0.75$) at $P_{\\rm orb}=57.41$\\,min as a function of age "
        "(radii from the \\texttt{MESA} grid; synchronous accretor; speeds in km\\,s$^{-1}$). $v_{\\rm esc}$ is the two-body accretor escape speed; "
        "$\\epsilon_{\\min}^{\\rm bin}$ uses instead the escape speed from the full binary potential (Sec.~\\ref{sec:energy}). Dashes: accretor overfills $L_1$ "
        "(no impact). $q_{\\max}$ values are scan results on a $\\Delta q=0.002$ grid at $\\Ma=80\\,\\MJ$ and carry that resolution.",
        "tab:age_phaseD", "rcccccccccccccccc",
        "$t_0$ & $R_{\\rm d,60}$ & $R_{\\rm a,80}$ & $\\zeta_{\\rm ad,60}$ & $q_{\\rm crit}^{f=0}$ & $f_{\\rm crit}^{\\rm pt}$ & $f_{\\rm crit}^{\\rm fl}$ & $v_{\\rm rot}$ & $v_{\\rm esc}$ & $f_{\\max}$ & $\\epsilon_{\\min}^{\\rm fl}$ & $\\epsilon_{\\min}^{\\rm fl,dyn}$ & $\\epsilon_{\\min}^{\\rm pt}$ & $\\epsilon_{\\min}^{\\rm bin}$ & $q_{\\max}^{\\rm fl}$ & $q_{\\max}^{\\rm fl,dyn}$",
        rows))

    # ------------------------------------------------------------ Table 4: candidates (+ L_spot coupling)
    L = sim.hotspot_bolometric_luminosity()
    rows, cand_data = [], []
    for c in res["candidates"]:
        Md, Ma = c["Md"], c["Ma"]
        by = c["by_age"]
        def g(age, key):
            return by[age][key] if age in by else float("nan")
        # hotspot-coupled requirement at 3 Gyr: Mdot_req = 2L / (v^2 - f_crit v_esc^2)
        en = sim.stream_energetics(Md, Ma, rad_fn(Ma, 3.0))
        f_c = g("3.0", "f_crit_fl")
        mreq = float("nan")
        if en["hit"] and np.isfinite(f_c):
            den = en["v_imp"] ** 2 - f_c * en["v_esc"] ** 2
            if den > 0:
                mreq = 2 * L / den * sim.YR_SEC / sim.M_JUP
        zs3 = zeta_fn(Md, 3.0)
        f_eval = f_c + 0.02 if f_c > 0 else 0.0
        m_gw = abs(sim.steady_state_mass_transfer_rate(Md, Ma, f_eval, "isotropic", zs3, Ra_J=rad_fn(Ma, 3.0), channels=("GW",), rho2=0.0))
        m_mb = abs(sim.steady_state_mass_transfer_rate(Md, Ma, f_eval, "isotropic", zs3, Ra_J=rad_fn(Ma, 3.0), channels=("GW", "MB"), rho2=0.0))
        rows.append([f"{Md}/{Ma}", n(c["q"]), n(c["t_contact_gyr"], 1), n(c["RL_d_RJ"]),
                     n(g("3.0", "f_crit_fl")), n(g("3.0", "f_crit_pt")), n(g("3.0", "f_max")),
                     n(g("2.0", "eps_min_fl"), 2), n(g("3.0", "eps_min_fl"), 2), n(g("5.0", "eps_min_fl"), 2),
                     n(g("3.0", "eps_min_fl_dyn"), 2), n(g("3.0", "eps_min_pt"), 2), n(g("3.0", "eps_min_fl_binary_escape"), 2),
                     sci(mreq, 1), sci(m_gw, 1), sci(m_mb, 1)])
        eta_req = (mreq - m_gw) / (m_mb - m_gw) if np.isfinite(mreq + m_gw + m_mb) and m_mb > m_gw else float("nan")
        cand_data.append({"Md": Md, "Ma": Ma, "Mdot_req_Lspot_3Gyr": mreq, "f_eval": f_eval, "Mdot_GW": m_gw,
                          "Mdot_GW_MB_eta1": m_mb, "eta_MB_required": eta_req})
    tex.append(table(
        "Candidate configurations at $P_{\\rm orb}=57.41$\\,min. $t_{\\rm cont}$: age at which an unstripped donor of mass $\\Md$ exactly fills $R_{L,\\rm d}$ "
        "(radius interpolated linearly between the $20/40/60/80\\,\\MJ$ tracks). $f_{\\rm crit}$, $f_{\\max}$ at $3$\\,Gyr; $\\epsilon_{\\min}$ at the ages indicated "
        "(fl: zero-AM floor, dyn: with the fast-rate shift $\\delta=0.025$, pt: point-source ejection, bin: binary-potential escape speed). "
        "$\\dot M_{\\rm req}=2L_{\\rm spot}/(v_{\\rm imp}^2-f_{\\rm crit}v_{\\rm esc}^2)$ is the minimum rate at which the stream can power both the "
        "$8904$\\,K hotspot ($L_{\\rm spot}=2.06\\times10^{31}$\\,erg\\,s$^{-1}$) and the unbinding of the critical fraction; "
        "$\\dot M_{\\rm GW}$ and $\\dot M_{\\rm GW+MB}$ are the quasi-steady rates (Eq.~\\ref{eq:mdot}, $\\eta_{\\rm MB}=1$) at $f=f_{\\rm crit}+0.02$ "
        "(or $f=0$ for conservative pairs), $\\rho=0$, in $\\MJ\\,{\\rm yr^{-1}}$.",
        "tab:candidates", "lcccccccccccccrrr",
        "$\\Md/\\Ma$ & $q$ & $t_{\\rm cont}$ & $R_{L,\\rm d}$ & $f_{\\rm crit}^{\\rm fl}$ & $f_{\\rm crit}^{\\rm pt}$ & $f_{\\max}$ & $\\epsilon^{\\rm fl}_{\\min}$ (2G) & $\\epsilon^{\\rm fl}_{\\min}$ (3G) & $\\epsilon^{\\rm fl}_{\\min}$ (5G) & $\\epsilon^{\\rm fl,dyn}_{\\min}$ (3G) & $\\epsilon^{\\rm pt}_{\\min}$ (3G) & $\\epsilon^{\\rm bin}_{\\min}$ (3G) & $\\dot M_{\\rm req}$ & $\\dot M_{\\rm GW}$ & $\\dot M_{\\rm GW+MB}$",
        rows))
    data["candidate_rates"] = cand_data

    # hotspot-implied minimum rates (patch geometry; R_bb range from the published fit)
    hs = {}
    for lab, R in (("lo", sim.R_BB_RANGE_JUP[0]), ("nom", sim.R_BB_JUP), ("hi", sim.R_BB_RANGE_JUP[1])):
        Ls = sim.hotspot_bolometric_luminosity(R_bb_J=R)
        hs[lab] = {"L_erg_s": Ls, "L_sphere_erg_s": 4 * Ls,
                   "Mdot_min_at_v177": sim.mdot_from_hotspot_luminosity(Ls, 176.9),
                   "Mdot_min_at_v206": sim.mdot_from_hotspot_luminosity(Ls, 206.1),
                   "Mdot_min_at_v220": sim.mdot_from_hotspot_luminosity(Ls, 219.6)}
    data["hotspot"] = hs

    # ------------------------------------------------------------ Table 5: rates vs age
    rows = []
    for r in res["age_scaling"]:
        def m(x):
            return sci(abs(x), 2) if np.isfinite(x) and x < 0 else "detached"
        rows.append([f"{r['age_gyr']:g}", n(r["rho_40_per_gyr"]), n(r["rho_60_per_gyr"]),
                     m(r["mdot_50_80_gw_no_rho"]), m(r["mdot_50_80_gw_with_rho"]),
                     m(r["mdot_60_80_gw_no_rho"]), m(r["mdot_60_80_gw_with_rho"]), m(r["mdot_60_80_mb_with_rho"])])
    g2a, g2b = [], []
    for (md_, ma_) in ((50, 80), (60, 80)):
        Md_, Ma_ = md_ * sim.M_JUP, ma_ * sim.M_JUP
        a_, _ = sim.orbital_elements(Md_, Ma_, sim.P_ORB_S)
        gg, _ = sim.damping_rates_gamma(Md_, Ma_, sim.P_ORB_S, a_ * float(sim.eggleton_roche_lobe(md_ / ma_)), 0.9 * sim.R_JUP, 0.0)
        (g2a if md_ == 50 else g2b).append(2 * gg * 1e9 * sim.YR_SEC)
    data["two_gamma_gw_per_gyr"] = {"50/80": g2a[0], "60/80": g2b[0]}
    tex.append(table(
        f"Quasi-steady mass-transfer rates $|\\Mdot_{{\\rm d}}|$ [$\\MJ\\,{{\\rm yr^{{-1}}}}$] with and without the contraction term $\\rho$ in Eq.~\\eqref{{eq:mdot}}. "
        f"Gravitational-wave driving is $2|\\Gamma_{{\\rm GW}}|={g2a[0]:.3f}$ (50/80) and ${g2b[0]:.3f}$\\,Gyr$^{{-1}}$ (60/80); "
        "the $60/80$ columns use $f=0.6$ (isotropic) and $\\zeta_{\\rm ad}$ at the given age. ``detached'': $|\\rho|>2|\\Gamma|$. "
        "GW+MB uses $\\eta_{\\rm MB}=1$ (saturated Sills et al.\\ torque). $\\rho_{40},\\rho_{60}$ in Gyr$^{-1}$.",
        "tab:age_phaseC", "rrrccccc",
        "$t_0$ [Gyr] & $\\rho_{40}$ & $\\rho_{60}$ & 50/80 GW ($\\rho{=}0$) & 50/80 GW (with $\\rho$) & 60/80 GW ($\\rho{=}0$) & 60/80 GW (with $\\rho$) & 60/80 GW+MB",
        rows))

    # ------------------------------------------------------------ Appendix A1: Roche-contact donor masses
    rows, contact = [], []
    for a in (1.5, 2.0, 3.0, 5.0, 8.0, 10.0):
        for Ma in (65, 70, 75, 80):
            fn = lambda md: rad_fn(md, a) - sim.binary_geometry(md, Ma)[4] * float(sim.eggleton_roche_lobe(md / Ma)) / sim.R_JUP
            try:
                md = float(brentq(fn, 25.0, 79.0))
            except ValueError:
                continue
            q = md / Ma
            zs = zeta_fn(md, a)
            def fcrit(shift=0.0, mode="isotropic", rho2=0.0):
                r = sim.critical_mass_loss_fraction(q, zs - shift, mode, rho2=rho2)
                return 0.0 if int(r["status"][0]) in (0, 3) else float(r["f"][0])
            Ra = rad_fn(Ma, a)
            en = sim.stream_energetics(md, Ma, Ra)
            enb = sim.stream_energetics(md, Ma, Ra, escape_model="binary")
            Rd = rad_fn(md, a)
            a_orb = sim.binary_geometry(md, Ma)[4] / sim.R_JUP
            rho2pt = float(sim.ejection_site_rho2(q, Ra / a_orb, "point"))
            f_fl, f_dyn, f_pt = fcrit(), fcrit(sim.DELTA_DYN_MEAS), fcrit(0.0, "isotropic", rho2pt)
            fm = en["f_max"] if en["hit"] else float("nan")
            rows.append([f"{a:g}", f"{Ma}", n(md, 1), n(q), n(Rd), n(Ra), n(zs), n(f_fl), n(f_pt), n(fm),
                         n(f_fl / fm, 2), n(f_dyn / fm, 2), n(f_pt / fm, 2), n(f_fl / enb["f_max"], 2)])
            contact.append({"age": a, "Ma": Ma, "Md_cont": md, "q": q, "f_crit_fl": f_fl, "f_max": fm})
    tex.append(table(
        "Exact Roche-lobe-filling donor masses at $P_{\\rm orb}=57.41$\\,min ($R_{\\rm d}(\\Md,t_0)=R_{L,\\rm d}$), with the corresponding critical fractions "
        "and required efficiencies. Radii are linearly interpolated between the $20/40/60/80\\,\\MJ$ \\texttt{MESA} tracks, so contact masses carry an "
        "uncertainty of order $\\pm1\\,\\MJ$ (see Sec.~\\ref{sec:limits}); the quoted precision is that of the code, not of the physics.",
        "tab:contact_age", "rrcccccccccccc",
        "$t_0$ [Gyr] & $\\Ma$ & $M_{\\rm d,cont}$ & $q$ & $R_{\\rm d}$ & $R_{\\rm a}$ & $\\zeta_{\\rm ad}$ & $f_{\\rm crit}^{\\rm fl}$ & $f_{\\rm crit}^{\\rm pt}$ & $f_{\\max}$ & $\\epsilon^{\\rm fl}_{\\min}$ & $\\epsilon^{\\rm fl,dyn}_{\\min}$ & $\\epsilon^{\\rm pt}_{\\min}$ & $\\epsilon^{\\rm bin}_{\\min}$",
        rows, midrules=tuple(range(4, len(rows), 4))))
    data["contact"] = contact

    # ------------------------------------------------------------ Appendix A2: q_crit and q_max vs age
    if not args.skip_qmax:
        rows, qtab = [], []
        qs = np.arange(0.60, 0.82, 0.002)
        for a in AG:
            qc = [sim.critical_mass_ratio(lambda md: zeta_fn(md, a), Ma_mjup=float(Ma)) for Ma in (65, 70, 75, 80)]
            qm = []
            for Ma in (65, 70, 75, 80):
                best = {"fl": float("nan"), "dyn": float("nan"), "pt": float("nan")}
                Ra = rad_fn(Ma, a)
                for q in qs:
                    md = q * Ma
                    st = sim.stream_energetics(md, Ma, Ra)
                    if not st["hit"]:
                        continue
                    a_orb = sim.binary_geometry(md, Ma)[4] / sim.R_JUP
                    r2 = float(sim.ejection_site_rho2(q, Ra / a_orb, "point"))
                    zs = zeta_fn(md, a)
                    for key, shift, rr in (("fl", 0.0, 0.0), ("dyn", sim.DELTA_DYN_MEAS, 0.0), ("pt", 0.0, r2)):
                        r = sim.critical_mass_loss_fraction(q, zs - shift, "isotropic", rho2=rr)
                        if int(r["status"][0]) != 2 and max(float(r["f"][0]), 0.0) <= st["f_max"]:
                            best[key] = float(q)
                qm.append(best)
            rows.append([f"{a:g}"] + [n(x) for x in qc] + [" / ".join(n(b[k]) for k in ("fl", "dyn", "pt")) for b in qm])
            qtab.append({"age": a, "q_crit": qc, "q_max": qm})
        tex.append(table(
            "Conservative critical mass ratio $q_{\\rm crit}^{f=0}$ and largest energetically allowed mass ratio $q_{\\max}(\\epsilon=1)$ at fixed accretor mass "
            "(zero-AM floor / floor with $\\delta=0.025$ / point-source ejection), from a $\\Delta q=0.002$ scan (so values are quantised to that step).",
            "tab:qcrit_qmax_age", "rcccccccc",
            "$t_0$ [Gyr] & $q_{\\rm crit}(65)$ & $q_{\\rm crit}(70)$ & $q_{\\rm crit}(75)$ & $q_{\\rm crit}(80)$ & $q_{\\max}(65)$ & $q_{\\max}(70)$ & $q_{\\max}(75)$ & $q_{\\max}(80)$",
            rows))
        data["qcrit_qmax"] = qtab

    # ------------------------------------------------------------ Appendix A3: composition / boundary variants
    v = json.load(open(ROOT / "out" / "zeta_variants.json"))
    M = np.array(v["M"])
    sel = (M >= 40) & (M <= 60)
    base = zeta_fn(55.0, 1.0)
    rows, vdata = [], []
    Ra80 = rad_fn(80.0, 1.0)
    en0 = sim.stream_energetics(60.0, 80.0, Ra80)
    for tag, label in (("base", "Baseline ($Z{=}0.02$, $\\tau_{\\rm atm}{=}100$)"), ("ZLO", "Low metallicity ($Z{=}0.0142$)"),
                       ("ZHI", "High metallicity ($Z{=}0.030$)"), ("ATMPH", "Photospheric boundary ($\\tau_{\\rm atm}{=}10$)")):
        d = 0.0 if tag == "base" else float(np.nanmedian(np.array(v[f"delta_ad_{tag}"], dtype=float)[sel]))
        zs = zeta_fn(60.0, 1.0) + d
        fc = float(sim.critical_mass_loss_fraction(0.75, zs, "isotropic", rho2=0.0)["f"][0])
        rows.append([label, n(d, 3), n(zs, 3), n(sim.critical_mass_ratio(lambda md: zeta_fn(md, 1.0) + d, 80.0)), n(fc), n(en0["f_max"]), n(fc / en0["f_max"], 2)])
        vdata.append({"tag": tag, "delta_zeta": d, "f_crit_60_80": fc})
    for dd, label in ((-sim.DELTA_DYN_MEAS, "Dynamical shift ($\\zeta_s-0.025$)"),):
        zs = zeta_fn(60.0, 1.0) + dd
        fc = float(sim.critical_mass_loss_fraction(0.75, zs, "isotropic", rho2=0.0)["f"][0])
        rows.append([label, n(dd, 3), n(zs, 3), n(sim.critical_mass_ratio(lambda md: zeta_fn(md, 1.0) + dd, 80.0)), n(fc), n(en0["f_max"]), n(fc / en0["f_max"], 2)])
    tex.append(table(
        "Sensitivity of the $60/80\\,\\MJ$, $1$\\,Gyr stability test to composition, outer boundary and rate. $\\Delta\\zeta$ is the median shift of $\\zeta_{\\rm ad}$ "
        "over $40$--$60\\,\\MJ$ measured in the $40$ and $60\\,\\MJ$ variant runs. No $80\\,\\MJ$ variant tracks exist, so the accretor radius and $f_{\\max}$ are held at the baseline "
        "values here (radius changes of the accretor are therefore \\emph{not} propagated).",
        "tab:variants", "lcccccc",
        "Case & $\\Delta\\zeta$ & $\\zeta_{\\rm ad,60}$ & $q_{\\rm crit}^{f=0}(80)$ & $f_{\\rm crit}^{\\rm fl}(60/80)$ & $f_{\\max}$ & $\\epsilon_{\\min}^{\\rm fl}$",
        rows))
    data["variants"] = vdata

    out = ROOT / "paper" / "tables_generated.tex"
    out.write_text("% AUTO-GENERATED by make_tables.py -- do not edit by hand.\n" + "\n".join(tex))
    split_tables(out.read_text())
    (ROOT / "results" / "tables.json").write_text(json.dumps(data, indent=1, default=float))
    print("wrote", out)


if __name__ == "__main__":
    main()
